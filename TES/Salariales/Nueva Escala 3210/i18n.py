def translate(text: str, language: str = "es", **values) -> str:
    if language.casefold() not in {"en", "english"}:
        translated = text
    else:
        translated = ENGLISH.get(text, COLUMN_LABELS.get(text, text))
        if translated == text:
            dynamic = (
                (r"Se detectaron (\d+) posibles duplicados\. Se conservan; revisa las filas de origen manualmente\.",
                 lambda m: f"Detected {m.group(1)} possible duplicates. They are retained; review source rows manually."),
                (r"Se detectaron discrepancias salariales en (\d+) grupos; la fuente no se corrige\.",
                 lambda m: f"Salary discrepancies were detected in {m.group(1)} groups; the source is not changed."),
                (r"Hay (\d+) filas con salario ausente o inválido; no se permite activar esta plantilla\.",
                 lambda m: f"{m.group(1)} rows have missing or invalid salaries; this template cannot be activated."),
                (r"Hojas de plantilla detectadas: (\d+)\.",
                 lambda m: f"Template sheets detected: {m.group(1)}."),
                (r"Filas utilizables: (\d+); salarios ausentes o inválidos: (\d+)\.",
                 lambda m: f"Usable rows: {m.group(1)}; missing or invalid salaries: {m.group(2)}."),
                (r"Posibles duplicados detectados: (\d+); no se elimina ninguna fila\.",
                 lambda m: f"Possible duplicates detected: {m.group(1)}; no rows are deleted."),
            )
            for pattern, render in dynamic:
                match = re.fullmatch(pattern, text)
                if match:
                    translated = render(match)
                    break
    try:
        return translated.format(**values)
    except (KeyError, ValueError):
        return translated


def format_currency(value: float, language: str = "es", *, decimals: int = 2) -> str:
    amount = float(value)
    if not math.isfinite(amount):
        return "—"
    return f"$ {amount:,.{decimals}f}"


def format_date(value: date, language: str = "es") -> str:
    return value.strftime("%Y-%m-%d" if language.casefold() in {"en", "english"} else "%d/%m/%Y")


def translate_dataframe(frame, language: str = "es"):
    """Devuelve una copia solo de presentación; nunca renombra el dato de origen."""
    if language.casefold() not in {"en", "english"}:
        return frame
    display = frame.copy()
    categorical_columns = {
        "Resultado", "status", "label", "Tipo de incidencia", "Estado de revisión",
        "Comprobación", "Tipo", "Estado", "Fuente del salario",
    }
    for column in categorical_columns.intersection(display.columns):
        display[column] = display[column].map(
            lambda value: ENGLISH.get(value, value) if isinstance(value, str) else value
        )
    return display.rename(columns={**COLUMN_LABELS, **{key: value for key, value in ENGLISH.items() if key in display.columns}})
